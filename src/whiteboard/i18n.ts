const dictionaries: Record<Language, Record<Key, Entry>> = { 'pt-BR': ptBR, en };

export type WbKey = Key;
export type WbTranslate = (key: Key, vars?: Record<string, string | number>) => string;

export function useWbT(): WbTranslate {
  const { language } = useLanguage();
  return useMemo<WbTranslate>(
    () => (key, vars) => {
      const entry = dictionaries[language][key] ?? ptBR[key];
      const text = typeof entry === 'string' ? entry : Number(vars?.count) === 1 ? entry.one : entry.other;
      return vars ? text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all)) : text;
    },
    [language],
  );
}
